<?php
/**
 * Writes the exam-season posts out as a plain SQL file.
 *
 * Some hosts have no terminal, and on those the file is imported through
 * phpMyAdmin instead of running cli/publish_exam_posts.php. Both routes put
 * exactly the same posts in the database.
 *
 *     php cli/make_posts_sql.php
 *
 * The file it writes is content/exam_posts_2027.sql.
 *
 * To export just one post (useful when the others are already live), pass its
 * slug. The file is then written to content/exam_posts_single.sql and holds
 * that one post only:
 *
 *     php cli/make_posts_sql.php neco-2027-ssce-registration-guidelines-in-plain-language
 */

$root = dirname(__DIR__);
$posts = require $root . '/content/exam_news_posts.php';

// Optional slug argument: export only that one post.
$onlySlug = $argv[1] ?? '';
$outFile  = 'content/exam_posts_2027.sql';

if ($onlySlug !== '') {
    $posts = array_values(array_filter($posts, function ($p) use ($onlySlug) {
        return $p['slug'] === $onlySlug;
    }));
    if (!$posts) {
        fwrite(STDERR, "No post with slug \"{$onlySlug}\" in content/exam_news_posts.php\n");
        exit(1);
    }
    $outFile = 'content/exam_posts_single.sql';
}

function sql_value(?string $value): string {
    if ($value === null) {
        return 'NULL';
    }
    return "'" . str_replace(["\\", "'"], ["\\\\", "''"], $value) . "'";
}

$lines = [];
$lines[] = '-- MyStudy Base - 2027 exam season posts';
$lines[] = '-- Generated by cli/make_posts_sql.php';
$lines[] = '-- Import through phpMyAdmin (select the database, then Import) if you cannot';
$lines[] = '-- run "php cli/publish_exam_posts.php" in the terminal.';
$lines[] = '-- Safe to import more than once: a post whose slug already exists is skipped.';
if ($onlySlug !== '') {
    $lines[] = '-- This file contains one post only: ' . $onlySlug;
}
$lines[] = '';
$lines[] = 'SET NAMES utf8mb4;';
$lines[] = 'SET FOREIGN_KEY_CHECKS = 0;';
$lines[] = '';

foreach ($posts as $post) {
    $slug    = $post['slug'];
    $title   = $post['title'];
    $excerpt = $post['excerpt'];
    $level   = $post['level'] === 'University' ? 'University' : 'Secondary';
    $isGeneral = !empty($post['university_general']) ? 1 : 0;

    $image    = 'assets/img/news/' . $post['banner']['file'];
    $imageUrl = '/assets/img/news/' . $post['banner']['file'];

    $content = '<p><img src="' . htmlspecialchars($imageUrl, ENT_QUOTES) . '" alt="'
        . htmlspecialchars($title, ENT_QUOTES) . '" width="1200" height="630" style="width:100%;height:auto;border-radius:14px;margin-bottom:1.2rem;"></p>'
        . "\n"
        . $post['content'];

    if (!empty($post['sources'])) {
        $content .= "\n<h3>Sources</h3>\n<ul>";
        foreach ($post['sources'] as $source) {
            $content .= "\n<li><a href=\"" . htmlspecialchars($source[1], ENT_QUOTES) . '" rel="nofollow noopener" target="_blank">'
                . htmlspecialchars($source[0], ENT_QUOTES) . '</a></li>';
        }
        $content .= "\n</ul>";
    }

    $content .= "\n<p style=\"font-size:0.85rem;color:#64748b;margin-top:2rem;\">"
        . "<em>This article covers the news of " . htmlspecialchars($post['date_label'] ?? date('j F Y'), ENT_QUOTES)
        . ". Last reviewed 26 November 2026. Always confirm fees, dates and rules on the examination body's own website before you act.</em></p>";

    $publishedAt = $post['date'] ?? date('Y-m-d H:i:s');
    $reviewedAt  = '2026-11-26 09:00:00';
    $content = '<!-- msb-updated: ' . $reviewedAt . ' -->' . "\n" . $content;

    $lines[] = '-- ' . $title;
    $lines[] = "INSERT INTO posts (title, slug, excerpt, content, author_id, level, university_id, is_university_general, created_at)";
    $lines[] = "SELECT " . sql_value($title) . ", " . sql_value($slug) . ", " . sql_value($excerpt) . ", " . sql_value($content)
        . ", 13, " . sql_value($level) . ", NULL, {$isGeneral}, " . sql_value($publishedAt);
    $lines[] = 'FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM posts WHERE slug = ' . sql_value($slug) . ');';
    $lines[] = '';
    // If an earlier copy of this file was already imported, the date is put
    // right here rather than left at the day the import happened.
    $lines[] = 'UPDATE posts SET created_at = ' . sql_value($publishedAt) . ' WHERE slug = ' . sql_value($slug) . ';';
    $lines[] = '';
    $lines[] = "INSERT INTO post_images (post_id, file_path, caption, sort_order)";
    $lines[] = "SELECT id, " . sql_value($image) . ", " . sql_value($title) . ", 0";
    $lines[] = 'FROM posts WHERE slug = ' . sql_value($slug)
        . ' AND NOT EXISTS (SELECT 1 FROM post_images WHERE file_path = ' . sql_value($image) . ' AND post_id = posts.id);';
    $lines[] = '';
}

$lines[] = 'SET FOREIGN_KEY_CHECKS = 1;';
$lines[] = '';

$path = $root . '/' . $outFile;
file_put_contents($path, implode("\n", $lines));

printf("%d posts written to %s (%s)\n", count($posts), $outFile, number_format(filesize($path)) . ' bytes');
