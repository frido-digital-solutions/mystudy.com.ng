<?php
/**
 * Writes the Study library out as a plain SQL file.
 *
 * The harvesters fill the library on a machine that can reach the source
 * sites. A host that cannot run them can still get the same library by
 * importing this file through phpMyAdmin, the same way the exam-season posts
 * were imported.
 *
 *     php cli/make_study_sql.php            writes content/study_library.sql
 *     php cli/make_study_sql.php --gzip     writes content/study_library.sql.gz
 *
 * The file is import-safe: a paper that is already in the library is skipped,
 * and a question that is already there is skipped, so running the import twice
 * does nothing the second time.
 */
require_once __DIR__ . '/../config/config.php';
require_once __DIR__ . '/../includes/study_schema.php';

$gzip = in_array('--gzip', array_slice($argv, 1), true);

msb_ensure_study_tables($pdo);

$papers = $pdo->query("
    SELECT id, exam, subject_slug, subject_name, year, paper_code, title,
           source, source_url, question_count
    FROM study_papers
    ORDER BY exam, subject_slug, year
")->fetchAll();

$questions = $pdo->query("
    SELECT q.paper_id, q.display_number, q.question, q.options_json,
           q.correct_option, q.explanation, q.topic, q.source_question_id,
           p.exam, p.subject_slug, p.year, p.paper_code, p.source
    FROM study_questions q
    JOIN study_papers p ON p.id = q.paper_id
    ORDER BY q.paper_id, q.display_number
")->fetchAll();

function study_sql_value($value): string
{
    if ($value === null) return 'NULL';
    return "'" . str_replace(["\\", "'"], ["\\\\", "''"], (string)$value) . "'";
}

$lines = [];
$lines[] = '-- MyStudy Base - Study library (real past questions and answers)';
$lines[] = '-- Generated by cli/make_study_sql.php';
$lines[] = '-- Import through phpMyAdmin: select the database, then Import.';
$lines[] = '-- Safe to import more than once - rows that already exist are skipped.';
$lines[] = '-- ' . count($papers) . ' papers, ' . count($questions) . ' questions.';
$lines[] = '';
$lines[] = 'SET NAMES utf8mb4;';
$lines[] = 'SET FOREIGN_KEY_CHECKS = 0;';
$lines[] = '';

// The tables come with the file, so that importing it into a server that has
// never seen the Study library works on its own.
$lines[] = 'CREATE TABLE IF NOT EXISTS `study_papers` (';
$lines[] = '    `id` INT(11) NOT NULL AUTO_INCREMENT,';
$lines[] = '    `exam` VARCHAR(10) NOT NULL,';
$lines[] = '    `subject_slug` VARCHAR(120) NOT NULL,';
$lines[] = '    `subject_name` VARCHAR(160) NOT NULL,';
$lines[] = '    `year` SMALLINT(6) NOT NULL,';
$lines[] = '    `paper_code` VARCHAR(40) NOT NULL DEFAULT \'objective\',';
$lines[] = '    `title` VARCHAR(255) NOT NULL,';
$lines[] = '    `source` VARCHAR(60) NOT NULL,';
$lines[] = '    `source_url` VARCHAR(500) DEFAULT NULL,';
$lines[] = '    `question_count` INT(11) NOT NULL DEFAULT 0,';
$lines[] = '    `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,';
$lines[] = '    PRIMARY KEY (`id`),';
$lines[] = '    UNIQUE KEY `uniq_paper` (`exam`, `subject_slug`, `year`, `paper_code`, `source`),';
$lines[] = '    INDEX `idx_paper_browse` (`exam`, `subject_slug`, `year`),';
$lines[] = '    INDEX `idx_paper_exam` (`exam`)';
$lines[] = ') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;';
$lines[] = '';
$lines[] = 'CREATE TABLE IF NOT EXISTS `study_questions` (';
$lines[] = '    `id` INT(11) NOT NULL AUTO_INCREMENT,';
$lines[] = '    `paper_id` INT(11) NOT NULL,';
$lines[] = '    `display_number` INT(11) NOT NULL,';
$lines[] = '    `question` TEXT NOT NULL,';
$lines[] = '    `options_json` TEXT NOT NULL,';
$lines[] = '    `correct_option` VARCHAR(8) NOT NULL DEFAULT \'\',';
$lines[] = '    `explanation` TEXT DEFAULT NULL,';
$lines[] = '    `topic` VARCHAR(190) DEFAULT NULL,';
$lines[] = '    `source_question_id` VARCHAR(64) DEFAULT NULL,';
$lines[] = '    PRIMARY KEY (`id`),';
$lines[] = '    UNIQUE KEY `uniq_question` (`paper_id`, `display_number`),';
$lines[] = '    INDEX `idx_question_paper` (`paper_id`),';
$lines[] = '    CONSTRAINT `study_questions_paper_fk`';
$lines[] = '        FOREIGN KEY (`paper_id`) REFERENCES `study_papers` (`id`) ON DELETE CASCADE';
$lines[] = ') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;';
$lines[] = '';

foreach ($papers as $p) {
    $lines[] = '-- ' . $p['exam'] . ' ' . $p['subject_name'] . ' ' . $p['year'] . ' (' . $p['source'] . ')';
    $lines[] = 'INSERT INTO study_papers (exam, subject_slug, subject_name, year, paper_code, title, source, source_url, question_count)';
    $lines[] = 'SELECT ' . study_sql_value($p['exam']) . ', ' . study_sql_value($p['subject_slug']) . ', '
        . study_sql_value($p['subject_name']) . ', ' . (int)$p['year'] . ', ' . study_sql_value($p['paper_code']) . ', '
        . study_sql_value($p['title']) . ', ' . study_sql_value($p['source']) . ', '
        . study_sql_value($p['source_url']) . ', ' . (int)$p['question_count'];
    $lines[] = 'FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM study_papers WHERE exam = ' . study_sql_value($p['exam'])
        . ' AND subject_slug = ' . study_sql_value($p['subject_slug'])
        . ' AND year = ' . (int)$p['year']
        . ' AND paper_code = ' . study_sql_value($p['paper_code'])
        . ' AND source = ' . study_sql_value($p['source']) . ');';
    $lines[] = '';
}

foreach ($questions as $q) {
    $lines[] = 'INSERT INTO study_questions (paper_id, display_number, question, options_json, correct_option, explanation, topic, source_question_id)';
    $lines[] = 'SELECT p.id, ' . (int)$q['display_number'] . ', ' . study_sql_value($q['question']) . ', '
        . study_sql_value($q['options_json']) . ', ' . study_sql_value($q['correct_option']) . ', '
        . study_sql_value($q['explanation']) . ', ' . study_sql_value($q['topic']) . ', '
        . study_sql_value($q['source_question_id']);
    $lines[] = 'FROM study_papers p WHERE p.exam = ' . study_sql_value($q['exam'])
        . ' AND p.subject_slug = ' . study_sql_value($q['subject_slug'])
        . ' AND p.year = ' . (int)$q['year']
        . ' AND p.paper_code = ' . study_sql_value($q['paper_code'])
        . ' AND p.source = ' . study_sql_value($q['source'])
        . ' AND NOT EXISTS (SELECT 1 FROM study_questions sq WHERE sq.paper_id = p.id AND sq.display_number = ' . (int)$q['display_number'] . ');';
    $lines[] = '';
}

$lines[] = 'SET FOREIGN_KEY_CHECKS = 1;';
$lines[] = '';

$path = $root = dirname(__DIR__) . '/content/study_library.sql';
$sql  = implode("\n", $lines);

if ($gzip) {
    $gz = gzencode($sql, 6);
    file_put_contents($path . '.gz', $gz);
    printf("%d papers, %d questions -> content/study_library.sql.gz (%s bytes)\n",
        count($papers), count($questions), number_format(strlen($gz)));
} else {
    file_put_contents($path, $sql);
    printf("%d papers, %d questions -> content/study_library.sql (%s bytes)\n",
        count($papers), count($questions), number_format(strlen($sql)));
}
